export function getCitiesByProvince(provinceName?: string | null): CityInfo[] {
  if (!provinceName || provinceName.trim() === "") return INDONESIA_CITIES;
  const pNorm = provinceName.trim().toLowerCase();
  return INDONESIA_CITIES.filter((c) => c.province.toLowerCase() === pNorm);
}

export function findProvinceByCity(cityName?: string | null): string | null {
  if (!cityName) return null;
  const cNorm = cityName.trim().toLowerCase();
  const found = INDONESIA_CITIES.find(
    (c) =>
      c.name.toLowerCase() === cNorm ||
      c.name.toLowerCase().includes(cNorm) ||
      cNorm.includes(c.name.toLowerCase().replace(/^(kota|kabupaten)\s+/i, ""))
  );
  return found ? found.province : null;
}
